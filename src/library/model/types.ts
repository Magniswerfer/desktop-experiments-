// ─── Library object model ─────────────────────────────────────────────────────
// The library is a unified index over ordinary filesystems and providers.
// Every concern is kept separate so it can be swapped for a real backend:
//
//   identity      LibItem (stable id, name, real path, provider)
//   storage       Provider + Availability            → providers.ts
//   content       Content (what a preview renders)    → provider.read()
//   metadata      tags (personal / ai) + summaries    → ai.ts, store.ts
//   relations     Relation (file ↔ file)              → relations.ts
//   collections   Collection (references, never moves)
//   usage         UsageEvent (observed facts)
//   assemblies    LibAssembly (from the window manager)
//   relevance     contextual ranking                  → relevance.ts

export type ProviderId = 'home' | 'downloads' | 'nextcloud' | 'git-orbit' | 'external';

export type ProviderKind = 'local' | 'downloads' | 'cloud' | 'git' | 'external';

export interface Provider {
  id: ProviderId;
  label: string;
  kind: ProviderKind;
  /** Mount point / root shown to the user, e.g. "/home/magnus" or "nextcloud://studio". */
  root: string;
  /** External drives can be unplugged; cloud can be offline. */
  connected: boolean;
}

/** Where the bytes actually are right now. Never pretend unavailable files are local. */
export type Availability =
  | 'local'            // on this machine's disk
  | 'cloud-downloaded' // cloud file with a local copy
  | 'cloud-online'     // cloud file, contents only on the server
  | 'unavailable'      // external drive not connected
  | 'git';             // tracked in a local git working tree

export type FileKind =
  | 'folder' | 'pdf' | 'markdown' | 'text' | 'code' | 'image'
  | 'doc' | 'sheet' | 'slides' | 'archive' | 'audio' | 'video';

/** How the file entered the library. */
export type Origin =
  | 'created'   // made by the user in a participating application (auto-saved)
  | 'received'  // downloaded, imported, attached — lands in the inbox
  | 'existing'; // pre-existing files discovered by indexing (repos, old folders)

/** Applications known to the desktop. Ids are stable; names are shown. */
export type AppId =
  | 'reader'    // PDF Reader
  | 'code'      // Code editor
  | 'notes'     // Notes (markdown)
  | 'browser'
  | 'terminal'
  | 'images'    // Image viewer / sketch
  | 'writer'    // Documents (office-like)
  | 'sheets'    // Spreadsheets
  | 'slides'    // Presentations
  | 'archive'   // Archive manager
  | 'player'    // Media player
  | 'mail'
  | 'messages';

export interface LibItem {
  id: string;
  kind: FileKind;
  /** Display name including extension for files ("orbit.ts"), plain for folders. */
  name: string;
  /** Lowercase extension without dot, '' for folders. */
  ext: string;
  /** Real absolute path / URI. Folders have their own path; files' parent is the folder with the matching path. */
  path: string;
  /** Parent folder id, or null at provider root level. */
  parentId: string | null;
  provider: ProviderId;
  availability: Availability;
  /** Bytes. Folders: 0 (aggregate size is computed from descendants). */
  size: number;
  /** When it entered the library (download time for received files). ms epoch. */
  added: number;
  modified: number;
  origin: Origin;
  /** For received items: where it came from, e.g. "Firefox · arxiv.org", "Mail · Ada Lindqvist". */
  source?: string;
  /** Seeded kept state for received items (user changes override in store). */
  kept?: boolean;
  /** Seeded personal tags (tag ids, kind 'personal'). */
  tags: string[];
  /** Seeded content-derived tags (tag ids, kind 'topic'). Shown as "suggested". */
  aiTags: string[];
  /** Short content summary (mock-generated by the analyzer). */
  summary?: string;
  /** Content for previews. Folders: null (children are computed). Unavailable items still carry
   *  a cached thumbnail-level content where realistic, but previews must say it's not readable. */
  content: Content | null;
  /** For created documents: version history (newest last). */
  versions?: { at: number; note: string }[];
  /** Created documents: the name follows the first line until the user renames. */
  autoName?: boolean;
  /** For git-tracked files. */
  git?: { status: 'clean' | 'modified' | 'untracked'; branch: string };
}

export interface Tag {
  id: string;
  label: string;
  /** personal: the user's own labels. topic: a content-derived concept vocabulary (AI may suggest these). */
  kind: 'personal' | 'topic';
}

// ─── Content shapes rendered by previews ─────────────────────────────────────

/** Procedural image description; the UI renders it as SVG (no binary assets). */
export interface ImageArt {
  style: 'screenshot' | 'sketch' | 'photo' | 'diagram' | 'moodboard' | 'chart' | 'logo' | 'wireframe' | 'scan';
  /** 0–360 base hue. */
  hue: number;
  /** Deterministic seed for layout variation. */
  seed: number;
  /** Optional short text drawn into the picture (e.g. a heading in a screenshot). */
  label?: string;
  /** Pixel dimensions of the "real" image (for aspect ratio + info pane). */
  w: number;
  h: number;
}

export type PdfBlock =
  | { k: 'title'; text: string }
  | { k: 'authors'; text: string }
  | { k: 'abstract'; text: string }
  | { k: 'h'; text: string }
  | { k: 'p'; text: string }
  | { k: 'quote'; text: string }
  | { k: 'figure'; art: ImageArt; caption: string }
  | { k: 'table'; rows: string[][] }
  | { k: 'refs'; items: string[] };

export interface PdfPage { blocks: PdfBlock[] }

export type DocBlock =
  | { k: 'title'; text: string }
  | { k: 'h'; text: string }
  | { k: 'p'; text: string }
  | { k: 'li'; text: string }
  | { k: 'table'; rows: string[][] }
  | { k: 'sign'; text: string };

export type Content =
  | { t: 'pdf'; pages: PdfPage[] }
  | { t: 'markdown'; text: string }
  | { t: 'text'; text: string }
  | { t: 'code'; lang: string; text: string }
  | { t: 'image'; art: ImageArt }
  | { t: 'doc'; blocks: DocBlock[] }
  | { t: 'sheet'; columns: string[]; rows: (string | number)[][] }
  | { t: 'slides'; slides: { title: string; bullets?: string[]; art?: ImageArt }[] }
  | { t: 'archive'; entries: { path: string; size: number }[] }
  | { t: 'media'; duration: number; artist?: string; note?: string; art?: ImageArt };

// ─── Relationships ───────────────────────────────────────────────────────────

/** File-to-file relations. 'used-together', 'collection' and 'assembly' relations are derived, not stored. */
export interface Relation {
  id: string;
  from: string;
  to: string;
  kind: 'references' | 'revision' | 'derived' | 'topic';
  /** explicit: the user or an application declared it. inferred: computed from content. */
  explicit: boolean;
  note?: string;
}

// ─── Usage (observed metadata) ───────────────────────────────────────────────

export interface UsageEvent {
  item: string;
  app: AppId;
  at: number;
  /** Active Assembly when the item was opened. */
  assembly: string | null;
  action: 'open' | 'edit' | 'save' | 'download';
}

// ─── Collections & assemblies ────────────────────────────────────────────────

export interface Collection {
  id: string;
  name: string;
  /** References to item ids (files or folders, any provider). Never moves anything. */
  items: string[];
  /** Assemblies this collection is associated with. */
  assemblies: string[];
  created: number;
  description?: string;
  /** If this was pinned from a dynamic view, the view's id. */
  pinnedFrom?: string;
}

export interface LibAssembly {
  id: string;
  name: string;
  ink: 'teal' | 'ultramarine' | 'oxide' | 'violet' | 'grass' | 'sienna' | 'chrome';
  /** Apps that usually live in this assembly. */
  apps: AppId[];
  /** Items explicitly attached to the assembly by the user or an application. */
  attached: string[];
}

export interface SeedData {
  providers: Provider[];
  tags: Tag[];
  items: LibItem[];
  relations: Relation[];
  usage: UsageEvent[];
  collections: Collection[];
  assemblies: LibAssembly[];
}
